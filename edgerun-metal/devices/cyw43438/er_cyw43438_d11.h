#ifndef ER_CYW43438_D11_H
#define ER_CYW43438_D11_H

/*
 * Purpose: name the CYW43438 D11 core registers used by the owned bring-up path.
 * Intention: keep the Pi board file free of anonymous MAC register offsets.
 */

#define ER_CYW43438_D11_MACCONTROL 0x00000120u
#define ER_CYW43438_D11_TPLATEWRPTR 0x00000130u
#define ER_CYW43438_D11_TPLATEWRDATA 0x00000134u
#define ER_CYW43438_D11_FRMTXSTATUS 0x00000170u
#define ER_CYW43438_D11_FRMTXSTATUS2 0x00000174u
#define ER_CYW43438_D11_FIFO64_BASE 0x00000200u
#define ER_CYW43438_D11_FIFO64_STRIDE 0x00000040u
#define ER_CYW43438_D11_FIFO64_PIO_TX_OFFSET 0x00000018u
#define ER_CYW43438_D11_PIO_TX_CONTROL_OFFSET 0x00000000u
#define ER_CYW43438_D11_PIO_TX_DATA_OFFSET 0x00000004u
#define ER_CYW43438_D11_XMTFIFOCMD 0x00000540u
#define ER_CYW43438_D11_TXE_STATUS 0x0000050eu
#define ER_CYW43438_D11_XMTFIFO_FRAME_CNT 0x00000522u
#define ER_CYW43438_D11_XMTFIFO_BYTE_CNT 0x00000524u
#define ER_CYW43438_D11_XMTFIFO_WR_PTR 0x0000052au
#define ER_CYW43438_D11_XMTFIFORDY 0x00000546u
#define ER_CYW43438_D11_TX_BCMC_FIFO 4u
#define ER_CYW43438_D11_MCTL_WAKE 0x04000000u
#define ER_CYW43438_D11_MCTL_IHR_EN 0x00000400u
#define ER_CYW43438_D11_MCTL_SHM_EN 0x00000100u
#define ER_CYW43438_D11_MCTL_EN_MAC 0x00000001u
#define ER_CYW43438_D11_TXFIFOCMD_RESET 0x8000u
#define ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_SHIFT 8u
#define ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_MASK 0x0700u
#define ER_CYW43438_D11_MACCONTROL_PROBE \
  (ER_CYW43438_D11_MCTL_WAKE | ER_CYW43438_D11_MCTL_IHR_EN | \
   ER_CYW43438_D11_MCTL_SHM_EN)
#define ER_CYW43438_D11_MACCONTROL_TX_ATTEMPT \
  (ER_CYW43438_D11_MACCONTROL_PROBE | ER_CYW43438_D11_MCTL_EN_MAC)
#define ER_CYW43438_D11_TX_BCMC_FIFO_SELECT \
  (ER_CYW43438_D11_TX_BCMC_FIFO << ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_SHIFT)
#define ER_CYW43438_D11_TX_BCMC_FIFO_RESET \
  (ER_CYW43438_D11_TXFIFOCMD_RESET | ER_CYW43438_D11_TX_BCMC_FIFO_SELECT)
#define ER_CYW43438_D11_TX_BCMC_PIO_TX_CONTROL \
  (ER_CYW43438_D11_FIFO64_BASE + \
   (ER_CYW43438_D11_TX_BCMC_FIFO * ER_CYW43438_D11_FIFO64_STRIDE) + \
   ER_CYW43438_D11_FIFO64_PIO_TX_OFFSET + \
   ER_CYW43438_D11_PIO_TX_CONTROL_OFFSET)
#define ER_CYW43438_D11_TX_BCMC_PIO_TX_DATA \
  (ER_CYW43438_D11_TX_BCMC_PIO_TX_CONTROL + \
   ER_CYW43438_D11_PIO_TX_DATA_OFFSET)

#endif
