#ifndef ER_CYW43438_D11_H
#define ER_CYW43438_D11_H

/*
 * Purpose: name the CYW43438 D11 core registers used by the owned bring-up path.
 * Intention: keep the Pi board file free of anonymous MAC register offsets.
 */

#define ER_CYW43438_D11_MACCONTROL 0x00000120u
#define ER_CYW43438_D11_XMTFIFOCMD 0x00000540u
#define ER_CYW43438_D11_XMTFIFORDY 0x00000546u
#define ER_CYW43438_D11_TX_BCMC_FIFO 4u
#define ER_CYW43438_D11_MCTL_WAKE 0x04000000u
#define ER_CYW43438_D11_MCTL_IHR_EN 0x00000400u
#define ER_CYW43438_D11_MCTL_SHM_EN 0x00000100u
#define ER_CYW43438_D11_TXFIFOCMD_RESET 0x8000u
#define ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_SHIFT 8u
#define ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_MASK 0x0700u
#define ER_CYW43438_D11_MACCONTROL_PROBE \
  (ER_CYW43438_D11_MCTL_WAKE | ER_CYW43438_D11_MCTL_IHR_EN | \
   ER_CYW43438_D11_MCTL_SHM_EN)
#define ER_CYW43438_D11_TX_BCMC_FIFO_SELECT \
  (ER_CYW43438_D11_TX_BCMC_FIFO << ER_CYW43438_D11_TXFIFOCMD_FIFOSEL_SHIFT)
#define ER_CYW43438_D11_TX_BCMC_FIFO_RESET \
  (ER_CYW43438_D11_TXFIFOCMD_RESET | ER_CYW43438_D11_TX_BCMC_FIFO_SELECT)

#endif
