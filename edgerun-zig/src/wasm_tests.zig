fn writeU32Leb(writer: anytype, value: u32) !void {
    var remaining = value;
    while (true) {
        var byte: u8 = @intCast(remaining & 0x7f);
        remaining >>= 7;
        if (remaining != 0) byte |= 0x80;
        try writer.writeByte(byte);
        if (remaining == 0) return;
    }
}

fn u32LebByteCount(value: u32) u32 {
    var remaining = value;
    var count: u32 = 1;
    while (remaining >= 0x80) {
        remaining >>= 7;
        count += 1;
    }
    return count;
}

const TestByteWriter = struct {
    bytes: []u8,
    len: usize = 0,

    fn writeByte(self: *TestByteWriter, byte: u8) !void {
        if (self.len >= self.bytes.len) return error.NoSpace;
        self.bytes[self.len] = byte;
        self.len += 1;
    }

    fn writeAll(self: *TestByteWriter, bytes: []const u8) !void {
        if (self.len + bytes.len > self.bytes.len) return error.NoSpace;
        @memcpy(self.bytes[self.len .. self.len + bytes.len], bytes);
        self.len += bytes.len;
    }

    fn written(self: TestByteWriter) []const u8 {
        return self.bytes[0..self.len];
    }
};

const GrowAuthority = struct {
    backing: []u8,
    requests: usize = 0,
};

const TableGrowAuthorityState = struct {
    max_entries: usize,
    requests: usize = 0,
};

fn grantGrow(context: ?*anyopaque, runtime: *wasm.Runtime, request: wasm.MemoryGrowRequest) wasm.Error!bool {
    const authority: *GrowAuthority = @ptrCast(@alignCast(context orelse return error.BadArgument));
    if (!request.valid()) return error.Corrupt;
    if (request.requested_bytes > authority.backing.len) return false;
    authority.requests += 1;
    runtime.memory = authority.backing[0..request.requested_bytes];
    return true;
}

fn grantTableGrow(context: ?*anyopaque, runtime: *wasm.Runtime, request: wasm.TableGrowRequest) wasm.Error!bool {
    _ = runtime;
    const authority: *TableGrowAuthorityState = @ptrCast(@alignCast(context orelse return error.BadArgument));
    if (!request.valid()) return error.Corrupt;
    if (request.requested_entries > authority.max_entries) return false;
    authority.requests += 1;
    return true;
}

