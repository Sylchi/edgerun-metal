fn testApp(memory: []u8, storage_bytes: []u8, slots: []store.Blob, execution_ticks: u64) App {
    const epoch = clock.Stamp{ .keeper = .{ .bytes = [_]u8{91} ++ [_]u8{0} ** 31 } };
    const app_id = identity.Identity.init(.app, identity.Source.prepare(.hash, &preimage.rawHash("wasm test app")).?, epoch).?;
    return App.initAllocated(
        app_id,
        BoundedArena.init(.{ .base = memory }),
        store.Store.init(.{ .base = storage_bytes }, slots),
        .{
            .memory_bytes = memory.len,
            .storage_bytes = storage_bytes.len,
            .storage_slots = slots.len,
            .execution_ticks = execution_ticks,
        },
    ).?;
}

fn executeRuntime(memory: []u8, ticks: *u64, wasm_bytes: []const u8) wasm.Error!i64 {
    var runtime = wasm.Runtime.init(memory, ticks);
    return wasm.executeExportI64(&runtime, wasm_bytes, "main");
}

