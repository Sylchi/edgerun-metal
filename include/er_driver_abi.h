#ifndef ER_DRIVER_ABI_H
#define ER_DRIVER_ABI_H

/*
 * Purpose: define the first stable Wasm driver ABI constants.
 * Intention: keep PCI discovery, MMIO addressing, and bus packet layouts explicit
 * across drivers, the metal runtime, and host-side decoding tools.
 */

#define ER_DRIVER_ABI_VERSION 1u

#define ER_DRIVER_ABI_BUS_KIND_PCI_CONFIG 1u
#define ER_DRIVER_ABI_BUS_KIND_MMIO32 2u
#define ER_DRIVER_ABI_BUS_KIND_IO_PORT 3u

#define ER_DRIVER_ABI_BUS_ACCESS_READ32 0x00000001u
#define ER_DRIVER_ABI_BUS_ACCESS_WRITE32 0x00000002u
#define ER_DRIVER_ABI_BUS_ACCESS_READ8 0x00000004u
#define ER_DRIVER_ABI_BUS_ACCESS_WRITE8 0x00000008u
#define ER_DRIVER_ABI_BUS_ACCESS_READ16 0x00000010u
#define ER_DRIVER_ABI_BUS_ACCESS_WRITE16 0x00000020u
#define ER_DRIVER_ABI_BUS_ACCESS_READ_ALL \
  (ER_DRIVER_ABI_BUS_ACCESS_READ8 | ER_DRIVER_ABI_BUS_ACCESS_READ16 | ER_DRIVER_ABI_BUS_ACCESS_READ32)
#define ER_DRIVER_ABI_BUS_ACCESS_WRITE_ALL \
  (ER_DRIVER_ABI_BUS_ACCESS_WRITE8 | ER_DRIVER_ABI_BUS_ACCESS_WRITE16 | ER_DRIVER_ABI_BUS_ACCESS_WRITE32)
#define ER_DRIVER_ABI_BUS_ACCESS_ALL \
  (ER_DRIVER_ABI_BUS_ACCESS_READ_ALL | ER_DRIVER_ABI_BUS_ACCESS_WRITE_ALL)

#define ER_DRIVER_ABI_BUS_WIDTH8_BYTES 1u
#define ER_DRIVER_ABI_BUS_WIDTH16_BYTES 2u
#define ER_DRIVER_ABI_BUS_WIDTH32_BYTES 4u

#define ER_DRIVER_ABI_BUS_PACKET_OP32_REQUEST 1u
#define ER_DRIVER_ABI_BUS_PACKET_OP32_RESPONSE 2u
#define ER_DRIVER_ABI_BUS_PACKET_IO_REQUEST 3u
#define ER_DRIVER_ABI_BUS_PACKET_IO_RESPONSE 4u

#define ER_DRIVER_ABI_BUS_STATUS_OK 0u
#define ER_DRIVER_ABI_BUS_STATUS_DENIED 1u
#define ER_DRIVER_ABI_BUS_STATUS_INVALID_ADDRESS 2u
#define ER_DRIVER_ABI_BUS_STATUS_INVALID_OPERATION 3u
#define ER_DRIVER_ABI_BUS_STATUS_IO_FAILED 4u

#define ER_DRIVER_ABI_EVENT_KIND_NONE 0u
#define ER_DRIVER_ABI_EVENT_KIND_IRQ 1u
#define ER_DRIVER_ABI_EVENT_KIND_QUEUE_USED 2u
#define ER_DRIVER_ABI_EVENT_KIND_DEVICE 3u

#define ER_DRIVER_ABI_BUS_ADDRESS_ABI_VERSION_OFFSET 0u
#define ER_DRIVER_ABI_BUS_ADDRESS_KIND_OFFSET 2u
#define ER_DRIVER_ABI_BUS_ADDRESS_ACCESS_FLAGS_OFFSET 4u
#define ER_DRIVER_ABI_BUS_ADDRESS_PCI_BUS_OFFSET 8u
#define ER_DRIVER_ABI_BUS_ADDRESS_PCI_DEV_OFFSET 12u
#define ER_DRIVER_ABI_BUS_ADDRESS_PCI_FUNC_OFFSET 16u
#define ER_DRIVER_ABI_BUS_ADDRESS_MMIO_BAR_OFFSET 20u
#define ER_DRIVER_ABI_BUS_ADDRESS_IO_PORT_OFFSET 24u
#define ER_DRIVER_ABI_BUS_ADDRESS_MMIO_BASE_OFFSET 32u
#define ER_DRIVER_ABI_BUS_ADDRESS_MMIO_LEN_OFFSET 40u
#define ER_DRIVER_ABI_BUS_ADDRESS_BYTES 48u

#define ER_DRIVER_ABI_BUS_OP_ABI_VERSION_OFFSET 0u
#define ER_DRIVER_ABI_BUS_OP_KIND_OFFSET 2u
#define ER_DRIVER_ABI_BUS_OP_ACCESS_OFFSET 4u
#define ER_DRIVER_ABI_BUS_OP32_ADDRESS_OFFSET 8u
#define ER_DRIVER_ABI_BUS_OP32_OFFSET_OFFSET 56u
#define ER_DRIVER_ABI_BUS_OP32_VALUE_OFFSET 64u
#define ER_DRIVER_ABI_BUS_OP32_BYTES 72u

#define ER_DRIVER_ABI_BUS_IO_OP_WIDTH_OFFSET 8u
#define ER_DRIVER_ABI_BUS_IO_OP_ADDRESS_OFFSET 16u
#define ER_DRIVER_ABI_BUS_IO_OP_OFFSET_OFFSET 64u
#define ER_DRIVER_ABI_BUS_IO_OP_VALUE_OFFSET 72u
#define ER_DRIVER_ABI_BUS_IO_OP_BYTES 80u

#define ER_DRIVER_ABI_BUS_PACKET_ABI_VERSION_OFFSET 0u
#define ER_DRIVER_ABI_BUS_PACKET_KIND_OFFSET 2u
#define ER_DRIVER_ABI_BUS_PACKET_STATUS_OFFSET 4u
#define ER_DRIVER_ABI_BUS_PACKET_ID_OFFSET 8u
#define ER_DRIVER_ABI_BUS_PACKET_OP_OFFSET 16u
#define ER_DRIVER_ABI_BUS_PACKET_OP32_RESULT_OFFSET 88u
#define ER_DRIVER_ABI_BUS_PACKET_OP32_BYTES 96u
#define ER_DRIVER_ABI_BUS_PACKET_IO_RESULT_OFFSET 96u
#define ER_DRIVER_ABI_BUS_PACKET_IO_BYTES 104u

#define ER_DRIVER_ABI_EVENT_ABI_VERSION_OFFSET 0u
#define ER_DRIVER_ABI_EVENT_KIND_OFFSET 2u
#define ER_DRIVER_ABI_EVENT_SOURCE_ID_OFFSET 4u
#define ER_DRIVER_ABI_EVENT_SEQUENCE_OFFSET 8u
#define ER_DRIVER_ABI_EVENT_ARG0_OFFSET 16u
#define ER_DRIVER_ABI_EVENT_ARG1_OFFSET 24u
#define ER_DRIVER_ABI_EVENT_BYTES 32u

#define ER_DRIVER_ABI_PCI_DISCOVERY_BUS_OFFSET 0u
#define ER_DRIVER_ABI_PCI_DISCOVERY_DEV_OFFSET 4u
#define ER_DRIVER_ABI_PCI_DISCOVERY_FUNC_OFFSET 8u
#define ER_DRIVER_ABI_PCI_DISCOVERY_TARGET_OFFSET 12u
#define ER_DRIVER_ABI_PCI_DISCOVERY_ID_OFFSET 16u
#define ER_DRIVER_ABI_PCI_DISCOVERY_COMMAND_OFFSET 20u
#define ER_DRIVER_ABI_PCI_DISCOVERY_CLASS_OFFSET 24u
#define ER_DRIVER_ABI_PCI_DISCOVERY_BAR_COUNT 6u
#define ER_DRIVER_ABI_PCI_DISCOVERY_BAR_BASE_OFFSET 32u
#define ER_DRIVER_ABI_PCI_DISCOVERY_BYTES 56u

#endif
